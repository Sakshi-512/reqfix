"""Tests for core.fixer.Fixer."""

from core.fixer import Fixer
from core.parser import Requirement
from core.resolver import ResolvedPackage


def _requirement(name: str, specifier: str | None, raw_line: str | None = None) -> Requirement:
    line = raw_line if raw_line is not None else f"{name}{specifier or ''}"
    return Requirement(name=name, specifier=specifier, raw_line=line)


def test_fix_one_pypi_error():
    resolved = ResolvedPackage(
        requirement=_requirement("missing-pkg", "==1.0"),
        available_versions=[],
        compatible_versions=[],
        latest_version=None,
        is_conflict=False,
        error="Package 'missing-pkg' not found on PyPI.",
    )

    suggestion = Fixer().fix_one(resolved)

    assert suggestion.suggested_version is None
    assert suggestion.fixed_line == "missing-pkg==1.0"
    assert "Could not fetch from PyPI" in suggestion.reason
    assert suggestion.was_conflict is False


def test_fix_one_conflict():
    resolved = ResolvedPackage(
        requirement=_requirement("pkg", "==99.0"),
        available_versions=["1.0.0", "2.0.0"],
        compatible_versions=[],
        latest_version="2.0.0",
        is_conflict=True,
    )

    suggestion = Fixer().fix_one(resolved)

    assert suggestion.was_conflict is True
    assert suggestion.suggested_version == "2.0.0"
    assert suggestion.fixed_line == "pkg==2.0.0"
    assert "No version satisfies" in suggestion.reason


def test_fix_one_unpinned():
    resolved = ResolvedPackage(
        requirement=_requirement("numpy", None, "numpy"),
        available_versions=["1.24.0", "2.0.0"],
        compatible_versions=["1.24.0", "2.0.0"],
        latest_version="2.0.0",
        is_conflict=False,
    )

    suggestion = Fixer().fix_one(resolved)

    assert suggestion.was_unpinned is True
    assert suggestion.suggested_version == "2.0.0"
    assert suggestion.fixed_line == "numpy==2.0.0"
    assert "No version was pinned" in suggestion.reason


def test_fix_one_healthy():
    resolved = ResolvedPackage(
        requirement=_requirement("requests", "==2.28.1"),
        available_versions=["2.28.0", "2.28.1", "2.29.0"],
        compatible_versions=["2.28.1"],
        latest_version="2.29.0",
        is_conflict=False,
    )

    suggestion = Fixer().fix_one(resolved)

    assert suggestion.was_conflict is False
    assert suggestion.was_unpinned is False
    assert suggestion.suggested_version == "2.28.1"
    assert suggestion.fixed_line == "requests==2.28.1"
    assert "latest compatible version" in suggestion.reason


def test_generate_fixed_requirements():
    fixer = Fixer()
    suggestions = [
        fixer.fix_one(
            ResolvedPackage(
                requirement=_requirement("flask", ">=2.0.0"),
                available_versions=["3.0.0"],
                compatible_versions=["3.0.0"],
                latest_version="3.0.0",
            )
        ),
        fixer.fix_one(
            ResolvedPackage(
                requirement=_requirement("numpy", None, "numpy"),
                available_versions=["2.0.0"],
                compatible_versions=["2.0.0"],
                latest_version="2.0.0",
            )
        ),
    ]

    content = fixer.generate_fixed_requirements(suggestions)

    assert content.startswith("# Generated by Reqfix\n")
    assert "# All packages pinned to latest compatible stable versions\n" in content
    assert "flask==3.0.0\n" in content
    assert "numpy==2.0.0\n" in content
    assert content.endswith("\n")
